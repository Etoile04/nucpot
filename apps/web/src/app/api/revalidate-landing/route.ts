import { createHash, timingSafeEqual } from 'crypto'
import { NextRequest, NextResponse } from 'next/server'
import { revalidatePath } from 'next/cache'

// NFM-5898 — post-cutover ISR warm-up endpoint.
//
// Every prod deploy serves the web image's BUILD-TIME prerender of the
// landing routes for up to ~30 min: the ISR freshness clock is anchored at
// `next build` (revalidate = 1800 on '/' and '/potentials'), and the build
// stage cannot reach the API (nucpot-prod-api DNS does not exist inside
// docker build), so home-data.ts fail-soft bakes empty sections — the
// 77150B cold payload decoded on the NFM-5897 thread. A plain GET cannot
// heal this early (it cache-HITs the same fresh entry); the deploy path
// needs FORCED on-demand revalidation, which is what this handler offers
// deploy_prod.sh after the health gates.
//
// '/browse' needs no entry of its own: it is an afterFiles alias rewrite of
// /potentials (NFM-5228, LEGACY_ALIAS_REWRITES) and shares the /potentials
// ISR entry, so revalidatePath('/potentials') regenerates the exact bytes
// the /browse monitor probe (scripts/health_check.py) fetches.
//
// Auth: shared per-deploy secret (ISR_WARMUP_TOKEN) generated by
// deploy_prod.sh, interpolated into this container by compose, and sent as
// the x-nfm-warmup-token header. Unset env = endpoint disabled (fail-closed)
// so ad-hoc compose invocations (staging, e2e, local dev) expose nothing.
// Both sides are hashed before timingSafeEqual so token length never leaks.
export const dynamic = 'force-dynamic'

const WARM_PATHS = ['/', '/potentials'] as const

function tokenMatches(received: string | null): boolean {
  const expected = process.env.ISR_WARMUP_TOKEN
  if (!expected || !received) {
    return false
  }
  const receivedDigest = createHash('sha256').update(received).digest()
  const expectedDigest = createHash('sha256').update(expected).digest()
  return timingSafeEqual(receivedDigest, expectedDigest)
}

export async function POST(request: NextRequest) {
  if (!process.env.ISR_WARMUP_TOKEN) {
    return NextResponse.json(
      { revalidated: [], error: 'ISR warm-up disabled: ISR_WARMUP_TOKEN not configured' },
      { status: 503 },
    )
  }

  const received = request.headers.get('x-nfm-warmup-token')
  if (!tokenMatches(received)) {
    return NextResponse.json({ revalidated: [], error: 'forbidden' }, { status: 403 })
  }

  for (const path of WARM_PATHS) {
    revalidatePath(path)
  }

  return NextResponse.json({ revalidated: [...WARM_PATHS] })
}
