"""Unit tests for scripts/check_prod_image_tag.py (NFM-4265).

Covers the 2026-09-04 NFM-4264 incident class: a 40-hex SHA pinned in
docker/.env.prod is silently inherited by any host-side
``docker compose --env-file docker/.env.prod up -d --build`` and re-tags
prod to a stale SHA while building current-tree content.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

SCRIPT_DIR = Path(__file__).resolve().parent.parent
SCRIPT_PATH = SCRIPT_DIR / "check_prod_image_tag.py"
DEPLOY_SCRIPT = SCRIPT_DIR / "deploy_prod.sh"
ENV_EXAMPLE = SCRIPT_DIR.parent / "docker" / ".env.prod.example"

# Stand-ins: OLD = the stale Sep-2 SHA from the incident, NEW = deploying SHA.
OLD_SHA = "dce00e62636f8df189d84e90df6d8377dc1f782d"
NEW_SHA = "8e29e906d300ce741ca32c4ba5c7d7558635aeba"


def guard_env(**extra: str) -> dict[str, str]:
    """Child env with any inherited PROD_IMAGE_TAG stripped."""
    env = {k: v for k, v in os.environ.items() if k != "PROD_IMAGE_TAG"}
    env.update(extra)
    return env


def run_guard(
    env_file: Path,
    *,
    expected: str | None = None,
    git_ref: str | None = None,
    repo: Path | None = None,
    shell_tag: str | None = None,
) -> subprocess.CompletedProcess[str]:
    cmd = [sys.executable, str(SCRIPT_PATH), "--env-file", str(env_file)]
    if expected is not None:
        cmd += ["--expected", expected]
    if git_ref is not None:
        cmd += ["--git-ref", git_ref]
    if repo is not None:
        cmd += ["--repo", str(repo)]
    env = guard_env()
    if shell_tag is not None:
        env["PROD_IMAGE_TAG"] = shell_tag
    return subprocess.run(cmd, capture_output=True, text=True, env=env)


def write_env_file(path: Path, tag_line: str | None) -> Path:
    lines = ["# generated by test", "PROD_API_HOST_PORT=8001"]
    if tag_line is not None:
        lines.append(tag_line)
    path.write_text("\n".join(lines) + "\n")
    return path


def make_git_repo(tmp_path: Path) -> tuple[Path, str]:
    repo = tmp_path / "repo"
    repo.mkdir()
    subprocess.run(["git", "init", "-q", str(repo)], check=True)
    subprocess.run(["git", "-C", str(repo), "config", "user.email", "t@example.com"], check=True)
    subprocess.run(["git", "-C", str(repo), "config", "user.name", "t"], check=True)
    (repo / "f.txt").write_text("x\n")
    subprocess.run(["git", "-C", str(repo), "add", "."], check=True)
    subprocess.run(["git", "-C", str(repo), "commit", "-q", "-m", "init"], check=True)
    head = subprocess.run(
        ["git", "-C", str(repo), "rev-parse", "HEAD"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    return repo, head


# --------------------------------------------------------------------------
# Check 1 — the env-file landmine (NFM-4264): a SHA in docker/.env.prod is
# always wrong, even a fresh one, even when the shell overrides it.
# --------------------------------------------------------------------------


def test_envfile_pinned_stale_sha_fails(tmp_path):
    env_file = write_env_file(tmp_path / ".env.prod", f"PROD_IMAGE_TAG={OLD_SHA}")
    proc = run_guard(env_file, expected=NEW_SHA)
    assert proc.returncode == 3
    combined = proc.stdout + proc.stderr
    assert "NFM-4264" in combined
    assert "latest" in combined
    assert "env-file" in combined or ".env.prod" in combined


def test_envfile_pinned_current_sha_still_fails(tmp_path):
    """A fresh SHA in the env-file goes stale on the next deploy — fail it too."""
    env_file = write_env_file(tmp_path / ".env.prod", f"PROD_IMAGE_TAG={NEW_SHA}")
    proc = run_guard(env_file, expected=NEW_SHA)
    assert proc.returncode == 3


def test_envfile_pinned_sha_fails_even_with_shell_override(tmp_path):
    env_file = write_env_file(tmp_path / ".env.prod", f"PROD_IMAGE_TAG={OLD_SHA}")
    proc = run_guard(env_file, expected=NEW_SHA, shell_tag=NEW_SHA)
    assert proc.returncode == 3


def test_envfile_quoted_sha_detected(tmp_path):
    env_file = write_env_file(tmp_path / ".env.prod", f'PROD_IMAGE_TAG="{OLD_SHA}"')
    proc = run_guard(env_file, expected=NEW_SHA)
    assert proc.returncode == 3


# --------------------------------------------------------------------------
# Check 2 — the effective tag (shell env > env-file > latest) must be either
# a non-SHA tag or the expected/target SHA.
# --------------------------------------------------------------------------


def test_envfile_latest_with_expected_passes(tmp_path):
    env_file = write_env_file(tmp_path / ".env.prod", "PROD_IMAGE_TAG=latest")
    proc = run_guard(env_file, expected=NEW_SHA)
    assert proc.returncode == 0
    assert "latest" in proc.stdout


def test_envfile_without_tag_passes(tmp_path):
    """Removing the line entirely is equally valid — compose falls back to latest."""
    env_file = write_env_file(tmp_path / ".env.prod", None)
    proc = run_guard(env_file, expected=NEW_SHA)
    assert proc.returncode == 0


def test_shell_sha_matching_expected_passes(tmp_path):
    env_file = write_env_file(tmp_path / ".env.prod", "PROD_IMAGE_TAG=latest")
    proc = run_guard(env_file, expected=NEW_SHA, shell_tag=NEW_SHA)
    assert proc.returncode == 0


def test_shell_stale_sha_mismatch_fails(tmp_path):
    env_file = write_env_file(tmp_path / ".env.prod", "PROD_IMAGE_TAG=latest")
    proc = run_guard(env_file, expected=NEW_SHA, shell_tag=OLD_SHA)
    assert proc.returncode == 2
    combined = proc.stdout + proc.stderr
    assert OLD_SHA[:8] in combined
    assert NEW_SHA[:8] in combined


def test_nonsha_tag_passes(tmp_path):
    """Version tags are not audit-destroying — only 40-hex SHAs are checked."""
    env_file = write_env_file(tmp_path / ".env.prod", "PROD_IMAGE_TAG=latest")
    proc = run_guard(env_file, expected=NEW_SHA, shell_tag="v1.2.3")
    assert proc.returncode == 0


def test_no_expected_resolves_git_ref(tmp_path):
    repo, head = make_git_repo(tmp_path)
    env_file = write_env_file(tmp_path / ".env.prod", "PROD_IMAGE_TAG=latest")

    matching = run_guard(env_file, git_ref="HEAD", repo=repo, shell_tag=head)
    assert matching.returncode == 0

    stale = run_guard(env_file, git_ref="HEAD", repo=repo, shell_tag=OLD_SHA)
    assert stale.returncode == 2


