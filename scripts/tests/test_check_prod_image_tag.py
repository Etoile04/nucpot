# --------------------------------------------------------------------------
# Wiring guard — executing deploy_prod.sh end to end on a fake host, and the
# tracked example must not model a SHA pin.
# --------------------------------------------------------------------------

# deploy_prod.sh prepends these to PATH before the inherited one, so a real
# docker there wins over any stub; the stub only serves hosts without one.
DEPLOY_PATH_PREFIXES = ("/usr/local/bin", "/usr/local/sbin", "/opt/homebrew/bin")


def write_executable(path: Path, body: str) -> Path:
    path.write_text(body)
    path.chmod(0o755)
    return path


def make_deploy_sandbox(
    tmp_path: Path, env_prod_line: str | None
) -> tuple[Path, Path, Path]:
    """Fake deploy host: HOME (so ``cd ~/Projects/nucpot`` lands in the
    sandbox) holding a real git repo with a local bare origin, plus a stub
    docker on PATH that records every invocation."""
    home = tmp_path / "home"
    repo = home / "Projects" / "nucpot"
    (repo / "scripts").mkdir(parents=True)
    (repo / "docker").mkdir(parents=True)
    shutil.copy2(DEPLOY_SCRIPT, repo / "scripts" / "deploy_prod.sh")
    shutil.copy2(SCRIPT_PATH, repo / "scripts" / "check_prod_image_tag.py")
    write_env_file(repo / "docker" / ".env.prod", env_prod_line)

    bare = tmp_path / "origin.git"
    subprocess.run(["git", "init", "-q", "--bare", str(bare)], check=True)
    subprocess.run(
        ["git", "-C", str(bare), "symbolic-ref", "HEAD", "refs/heads/main"], check=True
    )
    subprocess.run(["git", "-C", str(repo), "init", "-q"], check=True)
    subprocess.run(["git", "-C", str(repo), "config", "user.email", "t@example.com"], check=True)
    subprocess.run(["git", "-C", str(repo), "config", "user.name", "t"], check=True)
    subprocess.run(["git", "-C", str(repo), "remote", "add", "origin", str(bare)], check=True)
    subprocess.run(["git", "-C", str(repo), "add", "."], check=True)
    subprocess.run(["git", "-C", str(repo), "commit", "-q", "-m", "init"], check=True)
    subprocess.run(["git", "-C", str(repo), "branch", "-M", "main"], check=True)
    subprocess.run(["git", "-C", str(repo), "push", "-q", "origin", "main"], check=True)

    bin_dir = tmp_path / "stub-bin"
    bin_dir.mkdir()
    docker_log = tmp_path / "docker-calls.log"
    stub_body = (
        '#!/usr/bin/env bash\n'
        'printf "%s\\n" "docker $*" >> "$DOCKER_STUB_LOG"\n'
        "exit 0\n"
    )
    write_executable(bin_dir / "docker", stub_body)
    # A real docker (Docker Desktop) resolves compose via the DOCKER_CONFIG
    # override dir the script populates — it symlinks ~/.docker/cli-plugins/
    # docker-compose there, so provide one that answers the CLI's
    # docker-cli-plugin-metadata handshake.
    plugin_body = (
        '#!/usr/bin/env bash\n'
        'if [ "$1" = "docker-cli-plugin-metadata" ]; then\n'
        '  printf \'{"SchemaVersion":"0.1.0","Vendor":"test",'
        '"Version":"1.0","ShortDescription":"stub compose"}\\n\'\n'
        "  exit 0\n"
        "fi\n"
        'printf "%s\\n" "docker-compose $*" >> "$DOCKER_STUB_LOG"\n'
        "exit 0\n"
    )
    cli_plugins = home / ".docker" / "cli-plugins"
    cli_plugins.mkdir(parents=True)
    write_executable(cli_plugins / "docker-compose", plugin_body)
    return home, bin_dir, docker_log


def skip_if_host_docker_lacks_compose(bin_dir: Path) -> None:
    """The stub can only shadow docker on hosts with none in the PATH
    prefixes deploy_prod.sh hardcodes; probe a real one if it wins."""
    search_path = [Path(p) for p in DEPLOY_PATH_PREFIXES] + [
        bin_dir,
        Path("/usr/bin"),
        Path("/bin"),
    ]
    for directory in search_path:
        docker = directory / "docker"
        if not docker.is_file():
            continue
        if docker.parent == bin_dir:
            return
        probe = subprocess.run(
            [str(docker), "compose", "version"], capture_output=True
        )
        if probe.returncode != 0:
            pytest.skip(f"docker at {docker} cannot run 'compose version'")
        return


def run_deploy_prod(
    home: Path, bin_dir: Path, docker_log: Path, deploy_sha: str
) -> subprocess.CompletedProcess[str]:
    env = {k: v for k, v in os.environ.items() if k != "PROD_IMAGE_TAG"}
    env.update(
        {
            "HOME": str(home),
            "PATH": f"{bin_dir}{os.pathsep}/usr/bin:/bin",
            "DEPLOY_SHA": deploy_sha,
            "DOCKER_STUB_LOG": str(docker_log),
        }
    )
    script = home / "Projects" / "nucpot" / "scripts" / "deploy_prod.sh"
    return subprocess.run(
        ["/bin/bash", str(script)],
        capture_output=True,
        text=True,
        env=env,
        timeout=100,
    )


def test_deploy_prod_sh_aborts_before_build_when_env_prod_pins_sha(tmp_path):
    home, bin_dir, docker_log = make_deploy_sandbox(
        tmp_path, f"PROD_IMAGE_TAG={OLD_SHA}"
    )
    skip_if_host_docker_lacks_compose(bin_dir)
    proc = run_deploy_prod(home, bin_dir, docker_log, NEW_SHA)
    assert proc.returncode == 1
    combined = proc.stdout + proc.stderr
    assert "NFM-4265" in combined
    assert "Building nucpot-prod-api" not in proc.stdout
    if docker_log.exists():
        assert "build" not in docker_log.read_text()


def test_env_example_never_pins_sha():
    for raw in ENV_EXAMPLE.read_text().splitlines():
        line = raw.strip()
        if line.startswith("PROD_IMAGE_TAG="):
            value = line.partition("=")[2].strip().strip('"').strip("'")
            assert len(value) != 40 or not all(c in "0123456789abcdef" for c in value.lower()), (
                "docker/.env.prod.example must not model a SHA pin (NFM-4265)"
            )
